def _q(
    qid: str,
    node_key: str,
    qtype: str,
    level: str,
    text: str,
    answer: str,
    explanation: str,
    *,
    grade: int | None = None,
    options: list[str] | None = None,
    correct_index: int | None = None,
    hint: str = "",
    tiles: list[str] | None = None,
    assist_tiles: list[str] | None = None,
    distractors: list[str] | None = None,
    passage: str | None = None,
    rubric_keywords: list[list[str]] | None = None,
    min_chars: int = 0,
    sample_answer: str = "",
    scaffolds: list[str] | None = None,
) -> dict[str, Any]:
    g = grade if grade is not None else _infer_low_grade(node_key)
    item: dict[str, Any] = {
        "id": qid,
        "nodeKey": node_key,
        "grade": g,
        "questionType": qtype,
        "typeLabel": TYPE_LABELS.get(qtype, qtype),
        "level": level,
        "levelLabel": LEVEL_LABELS.get(level, level),
        "marks": TYPE_POINTS.get(qtype, 2),
        "text": text,
        "answer": answer,
        "explanation": explanation,
    }
    if options is not None:
        item["options"] = list(options)
        item["correctIndex"] = int(correct_index or 0)
    if hint:
        item["hint"] = hint
    if tiles is not None:
        item["tiles"] = list(tiles)
    if qtype in ("dictation_spell", "poem_fill"):
        if assist_tiles is not None:
            item["assistTiles"] = list(assist_tiles)
        else:
            seed_val = sum(ord(c) for c in qid)
            item["assistTiles"] = build_assist_tiles(answer, distractors, seed=seed_val)
    if passage:
        item["passage"] = passage
    if rubric_keywords:
        item["rubricKeywords"] = [list(grp) for grp in rubric_keywords]
    if min_chars:
        item["minChars"] = int(min_chars)
    elif qtype == "micro_writing":
        item["minChars"] = 12 if g == 1 else 20
    elif qtype == "reading_short":
        item["minChars"] = 6 if g == 1 else 8
    if qtype in ("micro_writing", "reading_short"):
        blocks = list(scaffolds or [])
        if blocks and not sample_answer:
            sample_answer = "".join(blocks)
        item["scaffolds"] = blocks
    if sample_answer:
        item["sampleAnswer"] = sample_answer
    return item


def _hanzi_tile_q(
    qid: str,
    node_key: str,
    level: str,
    word: str,
    pinyin: str,
    distractors: list[str],
    explanation: str,
    seed: int = 1,
) -> dict[str, Any]:
    chars = list(word) + list(distractors)
    tiles = _shuffle_deterministic(chars, seed + len(word))
    return _q(
        qid,
        node_key,
        "hanzi_tiles",
        level,
        f"看拼音「{pinyin}」，点击汉字块拼出正确的词语：",
        word,
        explanation,
        tiles=tiles,
        hint=f"点击字块拼出 {len(word)} 个字",
    )


def _poem_tile_q(
    qid: str,
    node_key: str,
    level: str,
    prompt: str,
    line: str,
    distractors: list[str],
    explanation: str,
    seed: int = 1,
) -> dict[str, Any]:
    chars = list(line) + list(distractors)
    tiles = _shuffle_deterministic(chars, seed + len(line))
    return _q(
        qid,
        node_key,
        "poem_tiles",
        level,
        prompt,
        line,
        explanation,
        tiles=tiles,
        hint=f"按顺序点击字块拼出 {len(line)} 个字",
    )


