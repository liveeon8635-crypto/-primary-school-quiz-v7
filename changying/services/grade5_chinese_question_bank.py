from __future__ import annotations

from typing import Any


CHINESE_G5_TEXTBOOK = "统编版（人民教育出版社）"


def _choice(
    *,
    unit: str,
    knowledge: str,
    text: str,
    answer: str,
    distractors: list[str],
    explanation: str,
    seed: int,
) -> dict[str, Any]:
    choices: list[str] = []
    for value in distractors:
        value = str(value)
        if value != answer and value not in choices:
            choices.append(value)
    for fallback in ("只看字数", "完全凭感觉", "忽略上下文", "以上都不合适"):
        if len(choices) >= 3:
            break
        if fallback != answer and fallback not in choices:
            choices.append(fallback)
    choices = choices[:3]
    correct_index = seed % 4
    options = list(choices)
    options.insert(correct_index, answer)
    return {
        "grade": 5,
        "subject": "语文",
        "textbook": CHINESE_G5_TEXTBOOK,
        "semester": "上册",
        "unit": unit,
        "knowledge": knowledge,
        "text": text,
        "options": options,
        "correct_index": correct_index,
        "explanation": explanation,
    }


def _unit_questions(
    unit: str,
    knowledge: str,
    rows: list[tuple[str, str, list[str], str]],
    start_seed: int,
) -> list[dict[str, Any]]:
    return [
        _choice(
            unit=unit,
            knowledge=knowledge,
            text=text,
            answer=answer,
            distractors=distractors,
            explanation=explanation,
            seed=start_seed + i,
        )
        for i, (text, answer, distractors, explanation) in enumerate(rows)
    ]


