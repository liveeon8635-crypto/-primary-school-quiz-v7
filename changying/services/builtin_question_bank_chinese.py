"""Grade 5 Chinese baseline question pack for the current PEP line.

The questions are original skill-aligned items, not copied textbook passages.
They are deliberately objective and unambiguous so automatic comprehensive
tests and module practice can feed the same student-feedback / reinforcement
loop already used by mathematics.
"""

from __future__ import annotations

from typing import Any

from changying.services.textbook_registry import CHINESE_G5_TEXTBOOK


def _spec(
    *,
    unit: str,
    knowledge: str,
    text: str,
    answer: str,
    distractors: list[str],
    explanation: str,
    seed: int,
) -> dict[str, Any]:
    answer = str(answer)
    unique: list[str] = []
    for value in distractors:
        value = str(value)
        if value != answer and value not in unique:
            unique.append(value)
    for fallback in ("无法确定", "以上都不对", "都可以", "都不正确"):
        if len(unique) >= 3:
            break
        if fallback != answer and fallback not in unique:
            unique.append(fallback)
    unique = unique[:3]
    correct_index = seed % 4
    options = list(unique)
    options.insert(correct_index, answer)
    return {
        "grade": 5,
        "subject": "语文",
        "textbook": CHINESE_G5_TEXTBOOK,
        "semester": "上册",
        "unit": unit,
        "knowledge": knowledge,
        "text": text,
        "options": options,
        "correct_index": correct_index,
        "explanation": explanation,
    }


